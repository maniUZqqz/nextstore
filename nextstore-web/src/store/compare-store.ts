/**
 * استور مقایسه‌ی محصولات (سمت کلاینت)
 * ---------------------------------------------------------------------------
 * فهرست محصولاتی که کاربر برای مقایسه انتخاب کرده است.
 *
 * ⚠️ برخلاف سبد و علاقه‌مندی، این فهرست **هرگز به سرور نمی‌رود**.
 *
 *    مقایسه یک کار لحظه‌ای است: کاربر سه گوشی را کنار هم می‌گذارد،
 *    تصمیم می‌گیرد و می‌رود. همگام‌سازی با حساب یعنی جدول مقایسه‌ی
 *    هفته‌ی پیش هفته‌ی بعد هم سر جایش است — که کمکی نمی‌کند و فقط
 *    یک جدول دیگر برای پاک کردن است.
 *
 * ⚠️ **نامک** ذخیره می‌شود نه شناسه.
 *
 *    صفحه‌ی مقایسه هر محصول را با `getProduct(slug)` می‌گیرد و API
 *    اندپوینت دسته‌جمعی ندارد. اگر شناسه ذخیره می‌شد، صفحه به یک
 *    اندپوینت تازه نیاز داشت. نامک ممکن است در پنل عوض شود؛ آن وقت
 *    آن یک قلم ۴۰۴ می‌گیرد و صفحه بی‌صدا از فهرست حذفش می‌کند.
 */

import { create } from 'zustand'
import { persist } from 'zustand/middleware'

/**
 * سقف تعداد محصولات قابل مقایسه.
 *
 * ⚠️ چهار، نه بیشتر. جدول مقایسه ستون‌محور است و روی نمایشگر ۱۴۴۰
 *    پیکسلی، ستون پنجم را به زیر خط تا می‌برد یا آن‌قدر باریک می‌کند
 *    که مقادیر نخوانا شوند. محدودیت در داده بهتر از اسکرول افقی
 *    بی‌پایان است.
 */
export const MAX_COMPARE = 4

interface CompareState {
  /** نامک محصولات انتخاب‌شده — به ترتیب افزودن */
  slugs: string[]
  /**
   * افزودن یا حذف.
   *
   * @returns `'added'` | `'removed'` | `'full'` — تا کامپوننت پیام
   *          مناسب نشان دهد. `'full'` یعنی سقف پر است و چیزی عوض نشد.
   */
  toggle: (slug: string) => 'added' | 'removed' | 'full'
  /** آیا این محصول در فهرست مقایسه است؟ */
  has: (slug: string) => boolean
  /** حذف صریح یک قلم — از خود صفحه‌ی مقایسه */
  remove: (slug: string) => void
  /** خالی کردن کامل */
  clear: () => void
}

export const useCompareStore = create<CompareState>()(
  persist(
    (set, get) => ({
      slugs: [],

      toggle: (slug) => {
        const current = get().slugs

        if (current.includes(slug)) {
          set({ slugs: current.filter((item) => item !== slug) })

          return 'removed'
        }

        /*
         * ⚠️ وقتی سقف پر است، **قدیمی‌ترین قلم جایگزین نمی‌شود**.
         *
         *    جایگزینی خودکار یعنی کاربر محصولی را که خودش انتخاب کرده
         *    بی‌خبر از دست می‌دهد. پیام صریح «سقف چهار محصول است» به او
         *    اجازه می‌دهد خودش تصمیم بگیرد کدام را بردارد.
         */
        if (current.length >= MAX_COMPARE) {
          return 'full'
        }

        set({ slugs: [...current, slug] })

        return 'added'
      },

      has: (slug) => get().slugs.includes(slug),

      remove: (slug) => set((state) => ({ slugs: state.slugs.filter((s) => s !== slug) })),

      clear: () => set({ slugs: [] }),
    }),
    {
      name: 'nextstore-compare',
      partialize: (state) => ({ slugs: state.slugs }),
    },
  ),
)
