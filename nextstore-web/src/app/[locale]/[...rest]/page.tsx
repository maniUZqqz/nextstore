import { notFound } from 'next/navigation'

/**
 * مسیر فراگیر — پل رساندن آدرس‌های نامعتبر به صفحه‌ی ۴۰۴ سفارشی
 * ---------------------------------------------------------------------------
 * ⚠️ بدون این فایل، `[locale]/not-found.tsx` کد مرده است.
 *
 *    Next.js فایل `not-found.tsx` یک بخش را فقط وقتی رندر می‌کند که
 *    `notFound()` از *داخل همان بخش* صدا زده شود. آدرسی مثل
 *    `/fa/چیزی-که-وجود-ندارد` با هیچ فایل مسیری مطابقت ندارد، پس
 *    اصلاً وارد بخش `[locale]` نمی‌شود و Next به ۴۰۴ توکار خودش
 *    برمی‌گردد: یک صفحه‌ی سفید انگلیسی با متن
 *    «404: This page could not be found.»
 *
 *    نتیجه‌ی عملی: صفحه‌ی ۴۰۴ دوزبانه‌ای که ساخته شده بود هرگز دیده
 *    نمی‌شد و کاربر گم‌شده هیچ راه بازگشتی نداشت — و چون خودِ کد
 *    سالم بود، در بازبینی کد هم به چشم نمی‌آمد.
 *
 *    این مسیر فراگیر آن آدرس‌ها را به داخل بخش `[locale]` می‌کشد و
 *    بلافاصله `notFound()` می‌زند، تا مرز درست فعال شود.
 *
 * ⚠️ این فایل هیچ مسیر واقعی‌ای را پنهان نمی‌کند: در Next.js مسیر
 *    مشخص‌تر همیشه بر مسیر فراگیر مقدم است، پس `/fa/products` و
 *    `/fa/admin/orders` مثل قبل به صفحه‌ی خودشان می‌روند.
 */
export default function CatchAllNotFound() {
  notFound()
}
