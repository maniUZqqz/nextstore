'use client'

/**
 * مرز خطای صفحات فروشگاه
 * ---------------------------------------------------------------------------
 * وقتی رندر یکی از صفحات `(shop)` throw کند، به‌جای کل صفحه فقط همین
 * جایگزین محتوا می‌شود.
 *
 * ⚠️ چرا اینجا و نه در سطح [locale]؟
 *    مرز خطا فرزندِ لایوت *بالای* خودش رندر می‌شود. داخل گروه (shop)
 *    یعنی هدر، فوتر و ناوبری پایین سر جایشان می‌مانند و کاربری که
 *    صفحه‌اش خطا داده می‌تواند بدون بازگشت دستی به مسیر دیگری برود.
 *    اگر این فایل یک سطح بالاتر بود، خطای یک صفحه‌ی محصول کل پوسته‌ی
 *    فروشگاه را هم پاک می‌کرد.
 *
 * ⚠️ مرز خطا در Next.js اجباراً کلاینتی است ('use client')، چون باید
 *    `reset` را به رویداد کلیک وصل کند.
 */

import { ErrorState } from '@/components/common/ErrorState'

export default function ShopError({
  error,
  reset,
}: {
  error: Error & { digest?: string }
  reset: () => void
}) {
  return <ErrorState error={error} reset={reset} />
}
