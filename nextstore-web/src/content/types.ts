/**
 * تایپ‌های مشترک محتوای صفحات ایستا
 * ---------------------------------------------------------------------------
 * چرا تایپ مشترک؟ چون هشت صفحه‌ی محتوایی ساختار یکسانی دارند و اگر
 * هرکدام شکل خودش را داشت، کامپوننت نمایش هم باید هشت‌بار نوشته
 * می‌شد. با تایپ مشترک، یک PageShell همه را رندر می‌کند.
 *
 * ⚠️ هر محتوا برای **هر دو زبان** الزامی است. اگر یکی اختیاری بود،
 *    جا انداختنش خطای کامپایل نمی‌داد و کاربر انگلیسی‌زبان صفحه‌ی
 *    خالی می‌دید — همان اشتباهی که در فرم محصول هم از آن پرهیز شد.
 */

import type { Locale } from '@/i18n/routing'

/** یک بند متنی با عنوان اختیاری. */
export interface ContentSection {
  /** عنوان بخش؛ اگر نباشد فقط پاراگراف رندر می‌شود */
  heading?: string
  /** پاراگراف‌ها — هر عضو یک <p> جدا می‌شود */
  paragraphs?: string[]
  /** فهرست نکته‌ای؛ زیر پاراگراف‌ها می‌آید */
  bullets?: string[]
}

/** ساختار یک صفحه‌ی محتوایی کامل. */
export interface ContentPage {
  /** عنوان صفحه — در <h1> و <title> استفاده می‌شود */
  title: string
  /** یک‌خط توضیح زیر عنوان و در متادیتای صفحه */
  subtitle: string
  /**
   * تاریخ آخرین بازنگری — فقط برای صفحات حقوقی معنا دارد.
   * صفحه‌ی قوانین بدون تاریخ، قابل استناد نیست.
   */
  updatedAt?: string
  sections: ContentSection[]
}

/** محتوای دوزبانه‌ی یک صفحه. */
export type LocalizedContent<T = ContentPage> = Record<Locale, T>

/**
 * انتخاب محتوای زبان جاری.
 *
 * تابع کوچکی است اما در هشت صفحه تکرار می‌شد؛ یک‌جا بودنش یعنی
 * اگر روزی زبان سومی اضافه شود، فقط همین‌جا تغییر می‌کند.
 */
export function pickLocale<T>(content: LocalizedContent<T>, locale: string): T {
  return content[locale as Locale] ?? content.fa
}
