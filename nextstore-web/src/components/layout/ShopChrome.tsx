/**
 * پوسته‌ی فروشگاه (هدر، فوتر، ناوبری پایین)
 * ---------------------------------------------------------------------------
 * ⚠️ مشکلی که این کامپوننت حل می‌کند:
 *
 *    پیش‌تر هدر و فوتر مستقیماً در لایوت [locale] بودند، یعنی روی
 *    **همه‌ی** مسیرها — از جمله پنل مدیریت. نتیجه این بود که بالای
 *    صفحه‌ی «مدیریت سفارش‌ها» نوار تبلیغاتی «ارسال رایگان سفارش‌های
 *    بالای ۵۰۰ هزار تومان» و منوی مگا دیده می‌شد و پایین آن فرم
 *    عضویت در خبرنامه و نشان‌های «ضمانت اصالت» — چیزهایی که برای
 *    یک ادمین در حال کار بی‌معنا و شلوغ‌کننده‌اند.
 *
 *    حالا این پوسته فقط دور مسیرهای فروشگاه پیچیده می‌شود و پنل
 *    مدیریت پوسته‌ی مینیمال خودش را دارد.
 *
 * چرا کامپوننت جدا و نه فقط لایوت گروه (shop)؟
 *    صفحه‌ی ۴۰۴ باید در سطح [locale] بماند تا آدرس‌های نامعتبر را
 *    هم بگیرد، اما همچنان به هدر و فوتر نیاز دارد. با یک کامپوننت
 *    مشترک، هر دو از یک منبع تغذیه می‌شوند و از دوباره‌نویسی خبری
 *    نیست.
 */

import { Header } from '@/components/layout/Header'
import { Footer } from '@/components/layout/Footer'
import { BottomNav } from '@/components/layout/BottomNav'
import { CompareBar } from '@/components/product/CompareBar'

export function ShopChrome({
  locale,
  children,
}: {
  locale: string
  children: React.ReactNode
}) {
  return (
    <>
      {/*
        هدر و فوتر در لایوت قرار دارند نه در تک‌تک صفحات.
        مزیت: هنگام ناوبری بین صفحات، هدر دوباره رندر نمی‌شود
        و وضعیت آن (مثلاً منوی باز) حفظ می‌ماند.
      */}
      <Header locale={locale} />

      {children}

      <Footer locale={locale} />

      {/*
        فاصله‌گذار انتهای صفحه.

        ⚠️ ناوبری پایین `fixed` است و روی جریان صفحه فضایی نمی‌گیرد،
           پس آخرین ۶۴ پیکسل هر صفحه زیرش پنهان می‌شد — در فوتر خط
           کپی‌رایت، و در صفحه‌ی مقایسه ردیف آخر جدول و دکمه‌های
           «مشاهده جزئیات».

           راه‌حل در ShopChrome است نه در تک‌تک صفحات: مشکل از پوسته
           می‌آید و حل‌کردنش در هر صفحه یعنی صفحه‌ی بعدی دوباره
           فراموشش می‌کند.

           `env(safe-area-inset-bottom)` هم اضافه می‌شود چون خود
           ناوبری آن را دارد؛ بدون آن روی آیفون یک نوار باریک کم می‌آمد.
      */}
      <div
        className="h-16 md:hidden"
        style={{ paddingBottom: 'env(safe-area-inset-bottom)' }}
        aria-hidden="true"
      />

      {/* ناوبری پایین — فقط در موبایل نمایش داده می‌شود */}
      <BottomNav />

      {/*
        نوار شناور مقایسه — تنها راه رسیدن به صفحه‌ی /compare.
        خودش تصمیم می‌گیرد کی دیده شود (فهرست خالی یا همان صفحه = هیچ).
      */}
      <CompareBar />
    </>
  )
}
