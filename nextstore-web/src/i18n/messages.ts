/**
 * انتخاب فضای‌نام‌های ترجمه برای ارسال به کلاینت
 * ---------------------------------------------------------------------------
 * ⚠️ مشکلی که این فایل حل می‌کند:
 *
 *    NextIntlClientProvider به‌صورت پیش‌فرض **تمام** پیام‌های ترجمه را
 *    در payload هر صفحه جاسازی می‌کند. اندازه‌گیری نشان داد:
 *
 *        کل فایل ترجمه           ۱۹.۶ کیلوبایت
 *        فضای‌نام admin           ۳.۴ کیلوبایت (۱۷.۵٪)
 *
 *    یعنی متن‌های پنل مدیریت روی صفحه‌ی اصلی، صفحه محصول و سبد خرید
 *    هم برای هر بازدیدکننده فرستاده می‌شد — بدون هیچ استفاده‌ای.
 *
 * راه‌حل: فضای‌نام‌های اختصاصی پنل مدیریت فقط در همان بخش ارسال شوند.
 *
 * چرا فقط admin و نه بقیه؟
 *    فضای‌نام‌هایی مثل cart یا product در کامپوننت‌های کلاینتی پراکنده‌اند
 *    (دکمه سبد در هدر، کارت محصول در چند صفحه) و حذفشان ریسک نمایش
 *    کلید خام به کاربر دارد. اما `admin` فقط در مسیر /admin استفاده
 *    می‌شود، پس حذفش کاملاً امن است.
 */

/** فضای‌نام‌هایی که فقط در پنل مدیریت استفاده می‌شوند. */
const ADMIN_ONLY_NAMESPACES = ['admin'] as const

/** نوع عمومی شیء پیام‌ها. */
type Messages = Record<string, unknown>

/**
 * حذف فضای‌نام‌های مخصوص پنل مدیریت.
 * در لایوت اصلی استفاده می‌شود تا صفحات فروشگاه سبک‌تر شوند.
 */
export function withoutAdminMessages(messages: Messages): Messages {
  const result: Messages = {}

  for (const [key, value] of Object.entries(messages)) {
    if (!ADMIN_ONLY_NAMESPACES.includes(key as never)) {
      result[key] = value
    }
  }

  return result
}
