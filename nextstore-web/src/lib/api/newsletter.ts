import { api } from './client'

/**
 * ثبت عضویت.
 *
 * ⚠️ پاسخ برای «تازه ثبت شد» و «از قبل عضو بود» یکسان است — عمدی، تا
 *    نشود با امتحان‌کردن ایمیل‌ها فهمید چه کسانی مشترک‌اند.
 */
export async function subscribeToNewsletter(email: string, locale?: string) {
  return api.post<{ message: string }>('/newsletter', { email }, { locale })
}
