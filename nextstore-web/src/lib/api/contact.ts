/**
 * ارسال پیام «تماس با ما»
 * ---------------------------------------------------------------------------
 * ⚠️ تنها مسیر عمومی پروژه که در دیتابیس **می‌نویسد**.
 *
 *    بک‌اند سقف سخت‌گیرانه‌ای رویش گذاشته (۳ در دقیقه، ۲۰ در ساعت روی
 *    هر IP) و پاسخ ۴۲۹ برمی‌گرداند. فرم باید این حالت را جدا از خطای
 *    اعتبارسنجی نشان دهد، وگرنه کاربر فکر می‌کند نوشته‌اش ایراد دارد
 *    و همان را بارها بازنویسی می‌کند.
 */

import { api } from './client'
import type { ContactMessageInput } from '@/types/contact'

/**
 * ثبت یک پیام تازه.
 *
 * ⚠️ پاسخ شناسه‌ای ندارد و نباید داشته باشد — فرستنده جایی برای دیدن
 *    پیامش ندارد. فقط پیام موفقیت برمی‌گردد.
 */
export async function sendContactMessage(input: ContactMessageInput, locale?: string) {
  return api.post<{ message: string }>('/contact', input, { locale })
}
