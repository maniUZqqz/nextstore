/**
 * نشانی پایه‌ی سایت
 * ---------------------------------------------------------------------------
 * ⚠️ چرا یک ماژول جدا برای یک خط؟
 *
 *    همین مقدار در سه جا تکرار شده بود — `layout.tsx`، `robots.ts` و
 *    `sitemap.ts` — و هر سه مقدار جایگزینِ **پورت ۳۰۰۰** داشتند در
 *    حالی که پروژه روی ۳۱۰۰ اجرا می‌شود (۳۰۰۰ روی این ماشین اشغال
 *    است).
 *
 *    نتیجه‌اش این بود که اگر `NEXT_PUBLIC_SITE_URL` تنظیم نشده باشد،
 *    نقشه‌ی سایت و `robots.txt` نشانی‌هایی می‌سازند که به هیچ‌جا نمی‌روند
 *    — و چون خطایی نمی‌دهند، تا وقتی کسی sitemap را باز نکند معلوم
 *    نمی‌شود.
 *
 * ⚠️ اسلش انتهایی حذف می‌شود تا `${SITE_URL}/fa` هرگز دو اسلش نگیرد.
 */
export const SITE_URL = (
  process.env.NEXT_PUBLIC_SITE_URL ?? 'http://localhost:3100'
).replace(/\/$/, '')

/**
 * تصویر پیش‌نمایش شبکه‌های اجتماعی برای یک زبان.
 *
 * ⚠️ نشانی **مطلق** برمی‌گرداند: شبکه‌های اجتماعی صفحه را از سرور
 *    خودشان می‌گیرند و مسیر نسبی برایشان بی‌معناست.
 */
export function ogImageUrl(locale: string): string {
  return `${SITE_URL}/og-${locale}.png`
}
