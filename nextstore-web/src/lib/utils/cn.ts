/**
 * ابزار ادغام کلاس‌های Tailwind
 * ---------------------------------------------------------------------------
 * مشکلی که این تابع حل می‌کند:
 *   وقتی کلاس‌ها را شرطی می‌سازیم، ممکن است دو کلاس متضاد کنار هم بیفتند:
 *       "px-4 px-6"   →  کدام برنده است؟ در CSS ترتیب تعریف مهم است نه ترتیب نوشتن
 *   نتیجه: رفتار غیرقابل پیش‌بینی.
 *
 * راه‌حل:
 *   clsx        → کلاس‌های شرطی را به یک رشته تبدیل می‌کند
 *   twMerge     → کلاس‌های متضاد Tailwind را تشخیص و آخری را نگه می‌دارد
 *
 * مثال:
 *   cn('px-4 py-2', isLarge && 'px-6')   →  'py-2 px-6'
 */

import { clsx, type ClassValue } from 'clsx'
import { twMerge } from 'tailwind-merge'

/**
 * کلاس‌های CSS را ادغام و تضادهای Tailwind را حل می‌کند.
 *
 * @param inputs هر تعداد کلاس، آرایه یا شیء شرطی
 * @returns رشته‌ی نهایی کلاس‌ها بدون تضاد
 */
export function cn(...inputs: ClassValue[]): string {
  return twMerge(clsx(inputs))
}
