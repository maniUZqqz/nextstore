<?php

/**
 * پیکربندی CORS (اشتراک منابع بین دامنه‌ها)
 * ===========================================================================
 * مشکلی که این فایل حل می‌کند:
 *   فرانت‌اند روی http://localhost:3000 اجرا می‌شود و بک‌اند روی
 *   http://localhost:8000. از نگاه مرورگر این دو «دامنه‌ی متفاوت» هستند
 *   و به‌صورت پیش‌فرض جاوااسکریپت اجازه‌ی خواندن پاسخ را ندارد.
 *
 *   بدون این تنظیم، در کنسول مرورگر می‌بینی:
 *       "Access to fetch has been blocked by CORS policy"
 *
 * ⚠️ نکته امنیتی برای محیط تولید:
 *    هرگز allowed_origins را روی '*' نگذار وقتی supports_credentials
 *    فعال است. آدرس دقیق دامنه‌ی فرانت‌اند را بنویس.
 */

return [

    /*
     * مسیرهایی که قوانین CORS روی آن‌ها اعمال می‌شود.
     * فقط API و مسیر احراز هویت Sanctum — بقیه مسیرها نیازی ندارند.
     */
    'paths' => ['api/*', 'sanctum/csrf-cookie', 'storage/*'],

    /*
     * متدهای HTTP مجاز.
     * '*' یعنی GET، POST، PUT، PATCH، DELETE و OPTIONS.
     */
    'allowed_methods' => ['*'],

    /*
     * دامنه‌هایی که اجازه‌ی فراخوانی API را دارند.
     * از متغیر محیطی خوانده می‌شود تا در تولید بدون تغییر کد قابل تنظیم باشد.
     */
    'allowed_origins' => array_filter(
        explode(',', env('CORS_ALLOWED_ORIGINS', 'http://localhost:3000,http://127.0.0.1:3000'))
    ),

    /*
     * الگوهای دامنه — برای دامنه‌هایی که آدرس ثابتی ندارند.
     */
    /*
     * ⚠️ بدون array_values.
     *
     *    array_filter کلیدها را حفظ می‌کند و اگر عضو اول حذف شود
     *    آرایه دیگر list نیست. ولی عضو اول اینجا ثابت است و هرگز
     *    فیلتر نمی‌شود، پس فراخوانی هیچ اثری نداشت — فقط خواننده
     *    را به این فکر می‌انداخت که حالتی هست که لازمش می‌کند.
     */
    'allowed_origins_patterns' => array_filter([
        /* دامنه‌های پیش‌نمایش ورسل که هر بار عوض می‌شوند */
        '#^https://.*\.vercel\.app$#',

        /*
         * ⚠️ فقط در محیط محلی: هر پورتی روی localhost یا 127.0.0.1.
         *
         *    مشکلی که حل می‌کند: فهرست ثابت بالا فقط پورت ۳۰۰۰ را
         *    می‌پذیرد. اگر پورت ۳۰۰۰ روی سیستم توسعه‌دهنده اشغال
         *    باشد (پروژه‌ی دیگری، یا سرور IPv6 دیگری روی همان پورت)،
         *    نکست خودکار روی پورت دیگری بالا می‌آید و از آن لحظه
         *    **همه‌ی درخواست‌های API با خطای CORS رد می‌شوند** —
         *    بدون هیچ نشانه‌ای در لاگ لاراول. تشخیصش وقت‌گیر است
         *    چون صفحه‌ها درست رندر می‌شوند و فقط داده نمی‌آید.
         *
         *    این الگو فقط وقتی فعال است که APP_ENV=local باشد؛ در
         *    تولید آرایه خالی می‌ماند و فقط دامنه‌های صریح مجازند.
         */
        env('APP_ENV') === 'local'
            ? '#^http://(localhost|127\.0\.0\.1)(:\d+)?$#'
            : null,
    ]),

    /*
     * هدرهایی که فرانت‌اند اجازه‌ی ارسالشان را دارد.
     * هدرهای اختصاصی ما:
     *   X-Locale     → زبان درخواستی
     *   X-Session-Id → شناسه نشست مهمان برای سبد خرید
     */
    'allowed_headers' => [
        'Accept',
        'Authorization',
        'Content-Type',
        'X-Requested-With',
        'X-Locale',
        'X-Session-Id',
        'Accept-Language',
    ],

    /*
     * هدرهایی که جاوااسکریپت فرانت‌اند اجازه‌ی *خواندن* آن‌ها را دارد.
     * بدون این، حتی اگر سرور هدر بفرستد، مرورگر آن را از JS پنهان می‌کند.
     */
    'exposed_headers' => [
        'Content-Language',
        'X-RateLimit-Limit',
        'X-RateLimit-Remaining',
    ],

    /*
     * مدت زمانی که مرورگر می‌تواند نتیجه‌ی درخواست preflight را کش کند (ثانیه).
     * ۱ ساعت یعنی مرورگر برای هر درخواست، یک OPTIONS اضافه نمی‌فرستد.
     */
    'max_age' => 3600,

    /*
     * ارسال کوکی و هدر Authorization بین دامنه‌ها.
     * چون از توکن Bearer استفاده می‌کنیم نه کوکی سشن، false کافی است
     * و امن‌تر هم هست.
     */
    'supports_credentials' => false,

];
