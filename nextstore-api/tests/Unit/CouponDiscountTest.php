<?php

/**
 * محاسبه‌ی مبلغ تخفیف — تست واحد.
 * ---------------------------------------------------------------------------
 * این منطق در `CouponType::discountFor` است و به دیتابیس نیازی ندارد،
 * پس تست واحد است نه Feature: اجرای مهاجرت‌ها برای آزمودن یک تابع
 * محاسباتی، وقت تلف کردن است.
 */

use App\Enums\CouponType;

describe('تخفیف درصدی', function () {
    it('درصد را درست حساب می‌کند', function () {
        expect(CouponType::Percent->discountFor(10_000_000, 20))->toBe(2_000_000);
    });

    it('سقف تخفیف را اعمال می‌کند', function () {
        /* ۲۰٪ از ۱۰۰ میلیون = ۲۰ میلیون، ولی سقف ۵ میلیون است */
        expect(CouponType::Percent->discountFor(100_000_000, 20, 5_000_000))
            ->toBe(5_000_000);
    });

    it('وقتی تخفیف زیر سقف باشد سقف را نادیده می‌گیرد', function () {
        expect(CouponType::Percent->discountFor(10_000_000, 10, 5_000_000))
            ->toBe(1_000_000);
    });

    /*
     * ⚠️ قیمت‌ها عدد صحیح ریال‌اند. اگر محاسبه با تقسیم اعشاری انجام
     *    می‌شد، ۳۳٪ از ۱۰۰ ریال عدد ۳۳.۰۰۰۰۰۰۰۰۰۰۰۰۰۴ می‌داد و آن
     *    خطا در فاکتور می‌نشست.
     */
    it('خروجی همیشه عدد صحیح است', function () {
        $discount = CouponType::Percent->discountFor(333, 33);

        expect($discount)->toBeInt()
            ->and($discount)->toBe(109);
    });
});

describe('تخفیف مبلغ ثابت', function () {
    it('همان مبلغ را برمی‌گرداند', function () {
        expect(CouponType::Fixed->discountFor(10_000_000, 2_000_000))->toBe(2_000_000);
    });

    /*
     * ⚠️ مهم‌ترین تست این فایل.
     *
     *    بدون این سقف، کوپن «۵۰۰ هزار تومان تخفیف» روی سبد ۲۰۰ هزار
     *    تومانی، جمع کل را **منفی** می‌کرد — و مبلغ منفی به درگاه
     *    پرداخت فرستاده می‌شد.
     */
    it('هرگز از جمع سبد بیشتر نمی‌شود', function () {
        expect(CouponType::Fixed->discountFor(2_000_000, 5_000_000))->toBe(2_000_000);
    });

    it('روی سبد خالی صفر می‌دهد', function () {
        expect(CouponType::Fixed->discountFor(0, 5_000_000))->toBe(0);
    });
});
