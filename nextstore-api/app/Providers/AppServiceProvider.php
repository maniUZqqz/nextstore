<?php

namespace App\Providers;

use Illuminate\Cache\RateLimiting\Limit;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\RateLimiter;
use Illuminate\Support\ServiceProvider;

/**
 * سرویس‌پرووایدر اصلی برنامه.
 * ---------------------------------------------------------------------------
 * محل تعریف تنظیمات سراسری‌ای که در زمان راه‌اندازی برنامه باید اعمال شوند.
 */
class AppServiceProvider extends ServiceProvider
{
    /** ثبت سرویس‌ها در کانتینر (فعلاً چیزی لازم نیست). */
    public function register(): void
    {
        //
    }

    /** اجرای تنظیمات پس از ثبت همه‌ی سرویس‌ها. */
    public function boot(): void
    {
        $this->configureRateLimiting();
    }

    /**
     * تعریف محدودیت‌های تعداد درخواست (Rate Limiting).
     *
     * چرا لازم است؟
     *   بدون محدودیت، یک اسکریپت می‌تواند هزاران درخواست در ثانیه بفرستد
     *   و سرور را از کار بیندازد یا کل کاتالوگ را استخراج کند (Scraping).
     *
     * استراتژی تفکیک کاربر:
     *   کاربر لاگین‌کرده → بر اساس شناسه کاربر (سهم اختصاصی خودش)
     *   کاربر مهمان      → بر اساس آدرس IP
     *
     *   دلیل: چند کاربر پشت یک IP مشترک (مثلاً یک شرکت) نباید سهم
     *   یکدیگر را مصرف کنند.
     */
    private function configureRateLimiting(): void
    {
        /*
         * محدودیت عمومی API.
         * کاربر مهمان: ۶۰ درخواست در دقیقه
         * کاربر واردشده: ۱۲۰ درخواست در دقیقه (سهم بیشتر چون شناخته‌شده است)
         */
        RateLimiter::for('api', function (Request $request) {
            $user = $request->user();

            return $user
                ? Limit::perMinute(120)->by('user:'.$user->id)
                : Limit::perMinute(60)->by('ip:'.$request->ip());
        });

        /*
         * محدودیت سخت‌گیرانه برای ورود و ثبت‌نام.
         * هدف: جلوگیری از حمله‌ی حدس رمز عبور (Brute Force).
         * ۵ تلاش در دقیقه برای هر ترکیب ایمیل و IP.
         */
        RateLimiter::for('auth', function (Request $request) {
            $key = strtolower((string) $request->input('email')).'|'.$request->ip();

            return Limit::perMinute(5)->by($key);
        });

        /*
         * درخواست پیوند بازیابی رمز — سطل جدا از ورود.
         *
         * ⚠️ چرا جدا و نه همان `auth`؟
         *
         *    `auth` روی ترکیب ایمیل و IP سقف ۵ در دقیقه دارد. اگر
         *    بازیابی رمز هم در همان سطل می‌نشست، کاربری که ۵ بار رمزش
         *    را اشتباه زده — یعنی **دقیقاً همان کسی که به بازیابی نیاز
         *    دارد** — از درخواست پیوند محروم می‌شد. منطق وارونه‌ای که
         *    فقط وقتی معلوم شد که تست سرتاسری پشت سر هم به ۴۲۹ خورد.
         *
         * ⚠️ دو کلید، دو خطر متفاوت:
         *
         *    روی **ایمیل** — تا کسی نتواند صندوق یک قربانی مشخص را با
         *    ایمیل‌هایی که از دامنه‌ی *ما* می‌آیند پر کند. سقف ساعتی
         *    است نه دقیقه‌ای، چون بمباران ایمیل کار کندی هم می‌تواند
         *    باشد.
         *
         *    روی **IP** — تا یک مهاجم نتواند همان کار را روی صدها
         *    نشانی مختلف انجام دهد و اعتبار دامنه‌ی فرستنده را بسوزاند.
         */
        RateLimiter::for('password-forgot', function (Request $request) {
            $email = strtolower(trim((string) $request->input('email')));

            return [
                Limit::perMinute(2)->by('pw-forgot:'.$email),

                /*
                 * ⚠️ ۱۰ در ساعت، نه ۵.
                 *
                 *    نسخه‌ی اول ۵ بود و در عمل بیش از حد تنگ درآمد:
                 *    کاربری که ایمیل را در پوشه‌ی هرزنامه نمی‌بیند و
                 *    چند بار تلاش می‌کند، تا یک ساعت قفل می‌شد — دقیقاً
                 *    همان کسی که به بازیابی نیاز دارد.
                 *
                 *    ۱۰ ایمیل در ساعت به یک نشانی، بمباران نیست؛ و سقف
                 *    IP در کنارش جلوی همان کار را روی صدها نشانی
                 *    می‌گیرد.
                 */
                Limit::perHour(10)->by('pw-forgot:'.$email),
                Limit::perHour(20)->by('pw-forgot-ip:'.$request->ip()),
            ];
        });

        /*
         * ثبت رمز تازه با توکن — سقف آزادتر.
         *
         * ⚠️ اینجا برخلاف ورود، سطح حمله‌ی حدس‌زدن عملاً وجود ندارد:
         *    توکن ۶۴ نویسه‌ی هگز است و حدس‌زدنش شدنی نیست. سقف فقط
         *    برای جلوگیری از سوءاستفاده است، نه امنیت رمز.
         *
         *    سخت‌گیری بی‌مورد اینجا هزینه دارد: کاربری که رمز تازه‌اش
         *    قواعد را رد نمی‌کند چند بار تلاش می‌کند، و نباید وسط کار
         *    قفل شود.
         */
        RateLimiter::for('password-reset', function (Request $request) {
            return Limit::perMinute(10)->by('pw-reset:'.$request->ip());
        });

        /*
         * محدودیت جستجو.
         * جستجو کوئری سنگینی است، پس سهم کمتری می‌گیرد.
         */
        /*
         * فرم تماس — سقف سخت‌گیرانه روی IP.
         *
         * ⚠️ ۳ در دقیقه و ۲۰ در ساعت، هر دو با هم.
         *
         *    فقط سقف دقیقه‌ای، ربات را متوقف نمی‌کند: کافی است بین هر
         *    ارسال ۲۱ ثانیه صبر کند تا شبانه هزار پیام بریزد. سقف
         *    ساعتی همان حلقه را می‌بندد، و آدم واقعی هرگز به هیچ‌کدام
         *    نمی‌خورد — کسی در یک ساعت بیست بار فرم تماس پر نمی‌کند.
         */
        RateLimiter::for('contact', function (Request $request) {
            return [
                Limit::perMinute(3)->by('contact:'.$request->ip()),
                Limit::perHour(20)->by('contact:'.$request->ip()),
            ];
        });

        RateLimiter::for('search', function (Request $request) {
            return Limit::perMinute(30)->by($request->ip());
        });
    }
}
