<?php

namespace App\Enums;

/**
 * روش ارسال سفارش.
 * ---------------------------------------------------------------------------
 * ⚠️ پیش‌تر این مقدار یک **رشته‌ی خام** بود که بین سرویس سفارش، قواعد
 *    اعتبارسنجی و ستون دیتابیس دست‌به‌دست می‌شد.
 *
 *    نتیجه‌اش این بود: صفحه‌ی سفارش کاربر و فاکتور، عبارت «standard» را
 *    عیناً به مشتری فارسی‌زبان نشان می‌دادند. هیچ خطایی هم نمی‌داد —
 *    فقط زشت بود و در فاکتور، غیرحرفه‌ای.
 *
 * ⚠️ برچسب از **بک‌اند** می‌آید نه از نگاشت در فرانت. همان قاعده‌ای که
 *    برای وضعیت سفارش، تیکت و اعلان به کار رفت: نگاشت دوم یعنی افزودن
 *    روش سوم دو جا تغییر می‌خواهد و یکی همیشه جا می‌ماند.
 */
enum ShippingMethod: string
{
    /** ارسال عادی — بالای آستانه رایگان می‌شود. */
    case Standard = 'standard';

    /**
     * ارسال سریع.
     *
     * ⚠️ عمداً هرگز رایگان نمی‌شود، حتی بالای آستانه: تخفیف ارسال فقط
     *    روی روش عادی است و هزینه‌ی واقعی تحویل فوری را پوشش می‌دهد.
     */
    case Express = 'express';

    /** برچسب فارسی یا انگلیسی. */
    public function label(string $locale = 'fa'): string
    {
        return match ($this) {
            self::Standard => $locale === 'fa' ? 'ارسال عادی' : 'Standard shipping',
            self::Express => $locale === 'fa' ? 'ارسال سریع' : 'Express shipping',
        };
    }

    /** توضیح کوتاه زمان تحویل. */
    public function description(string $locale = 'fa'): string
    {
        return match ($this) {
            self::Standard => $locale === 'fa' ? '۳ تا ۵ روز کاری' : '3 to 5 working days',
            self::Express => $locale === 'fa' ? '۱ تا ۲ روز کاری' : '1 to 2 working days',
        };
    }
}
